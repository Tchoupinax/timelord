<script lang="ts" setup>
import { computed, onMounted, onUnmounted, ref } from "vue";

import type { ActivityItem, ActivityResponse } from "~/types/external-activity";

const config = useRuntimeConfig();
const activities = ref<ActivityItem[]>([]);
const selectedJobIdToShowLogs = ref("");

const hasLiveActivity = computed(() =>
  activities.value.some(
    item => item.type === "job_running" || item.type === "job_queued",
  ),
);

const showLogsForJobId = (jobId: string) => {
  selectedJobIdToShowLogs.value = jobId;
};

const refreshActivity = async () => {
  try {
    const res = await fetch(`${config.public.apiEndpoint}/activity`, {
      credentials: "include",
    });
    const data = (await res.json()) as ActivityResponse;
    activities.value = data.activities ?? [];
  } catch (err) {
    console.error("Failed to refresh activity:", err);
  }
};

const { data } = await useFetch<ActivityResponse>(
  `${config.public.apiEndpoint}/activity`,
  {
    credentials: "include",
  },
);

activities.value = data.value?.activities ?? [];

let pollInterval: ReturnType<typeof setInterval> | null = null;

onMounted(() => {
  pollInterval = setInterval(refreshActivity, 3000);
});

onUnmounted(() => {
  if (pollInterval) {
    clearInterval(pollInterval);
  }
});
</script>
