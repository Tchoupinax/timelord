<script lang="ts" setup>
import { useRuntimeConfig } from "#app";

const config = useRuntimeConfig();
const cleanQueuesModalOpened = ref(false);
const cleaningQueues = ref(false);
const { notify } = useNotification();

const confirmCleanQueues = async () => {
  cleaningQueues.value = true;
  try {
    const res = await fetch(`${config.public.apiEndpoint}/jobs/queue`, {
      credentials: "include",
      method: "DELETE",
    });
    const data = await res.json();
    if (!res.ok) {
      notify({
        title: "Failed to clear queue",
        type: "error",
        text: data?.message ?? "Unknown error",
      });
      return;
    }
    cleanQueuesModalOpened.value = false;
    notify({
      title: "Queues cleared",
      type: "success",
      text:
        data?.clearedCount != null
          ? `${data.clearedCount} job(s) removed`
          : "Done",
    });
  } catch (err) {
    notify({
      title: "Failed to clear queue",
      type: "error",
      text: err instanceof Error ? err.message : "Network error",
    });
  } finally {
    cleaningQueues.value = false;
  }
};
</script>
